WIDTH = 5
HEIGHT = 7
UNKNOWN = ("11111", "10001", "10001", "10001", "10001", "10001", "11111")


def glyph(character):
    return GLYPHS.get(character.upper(), UNKNOWN)


def measure(text, spacing=1):
    """Width in glyph pixels of `text` rendered with `spacing` between."""
    if not text:
        return 0
    return len(text) * WIDTH + (len(text) - 1) * spacing


def points(text, spacing=1):
    """Lit (x, y) glyph pixels, origin top-left, y down."""
    lit = []
    cursor = 0
    for character in text:
        rows = glyph(character)
        for y, row in enumerate(rows):
            for x, cell in enumerate(row):
                if cell == "1":
                    lit.append((cursor + x, y))
        cursor += WIDTH + spacing
    return lit
